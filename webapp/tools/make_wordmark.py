#!/usr/bin/env python3
"""Cut Inter Display down to the wordmark's letters and write webapp/app/wordmark.css.

The wordmark, "micro-FT8", is the app's header when it runs from the Home Screen and the basis of its icon
(docs/architecture/webapp.md, Home Screen). The app is served by the sidekick, often with no internet, so the
face ships inside the app: two weights, cut down to the nine letters, embedded as data in one stylesheet, a few KB.

Inter is by The Inter Project Authors under the SIL Open Font License 1.1 (webapp/tools/Inter-LICENSE.txt).
The release is pinned by its SHA-256; run again only to change the face, the weights or the letters.

  python3 -m pip install fonttools brotli      # once
  python3 webapp/tools/make_wordmark.py         # downloads the release, or --zip a copy of it
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import io
import sys
import urllib.request
import zipfile
from pathlib import Path

RELEASE = "https://github.com/rsms/inter/releases/download/v4.1/Inter-4.1.zip"
SHA256 = "9883fdd4a49d4fb66bd8177ba6625ef9a64aa45899767dde3d36aa425756b11e"
LETTERS = "micro-FT8"
FAMILY = "micro-FT8 Wordmark"
WEIGHTS = {500: "extras/ttf/InterDisplay-Medium.ttf", 800: "extras/ttf/InterDisplay-ExtraBold.ttf"}

TOOLS = Path(__file__).resolve().parent
OUT = TOOLS.parent / "app" / "wordmark.css"


def subset_woff2(ttf: bytes) -> bytes:
    from fontTools import subset  # imported here so --help works without it
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.name_IDs = ["*"]  # keep the copyright and licence names the OFL asks to travel with the font
    opts.layout_features = ["kern", "liga", "calt"]
    font = subset.load_font(io.BytesIO(ttf), opts)
    sub = subset.Subsetter(opts)
    sub.populate(text=LETTERS)
    sub.subset(font)
    out = io.BytesIO()
    subset.save_font(font, out, opts)
    return out.getvalue()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--zip", type=Path, help="a copy of the Inter 4.1 release zip, instead of downloading it")
    args = ap.parse_args()
    data = args.zip.read_bytes() if args.zip else urllib.request.urlopen(RELEASE, timeout=60).read()
    got = hashlib.sha256(data).hexdigest()
    if got != SHA256:
        print(f"error: the release's SHA-256 is {got}, expected {SHA256}", file=sys.stderr)
        return 1
    z = zipfile.ZipFile(io.BytesIO(data))
    (TOOLS / "Inter-LICENSE.txt").write_bytes(z.read("LICENSE.txt"))
    faces = []
    for weight, member in WEIGHTS.items():
        woff2 = subset_woff2(z.read(member))
        faces.append(f"@font-face{{font-family:'{FAMILY}';font-style:normal;font-weight:{weight};font-display:block;"
                     f"src:url(data:font/woff2;base64,{base64.b64encode(woff2).decode()}) format('woff2')}}")
        print(f"weight {weight}: {len(woff2)} bytes")
    OUT.write_text(
        "/* Generated by webapp/tools/make_wordmark.py; do not edit. Inter Display 4.1, copyright The Inter Project\n"
        "   Authors, SIL Open Font License 1.1 (webapp/tools/Inter-LICENSE.txt), cut down to the letters of the\n"
        f"   wordmark, \"{LETTERS}\". */\n" + "\n".join(faces) + "\n")
    print(f"wrote {OUT.relative_to(TOOLS.parents[1])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
